    recorded = QUEUE_TYPES["durability"]["exclusiveAutoDeleteOrTransient"]
    assert "must keep them classic" in recorded

    transport = await _one_queue(**asked)
    assert QUEUE_TYPE_ARG not in transport.queues[QUEUE].args
    assert _kind(transport, QUEUE) == "classic"
