async def _declared(*, retry: RetryPolicy | None) -> FakeTransport:
    """The fixture's topology, applied to a transport that records rather than connects."""
    transport = FakeTransport()
    await (
        Topology()
        .exchange("orders", "topic")
        .queue(TOPOLOGY["sourceQueue"], dead_letter=True, retry=retry)
        .binding(TOPOLOGY["sourceQueue"], "orders", "order.*")
    ).apply(transport)
    return transport


def _expect(entries: list[dict[str, Any]], *by: str) -> list[dict[str, Any]]:
    return [entry for entry in entries if entry["declaredBy"] in by]


def test_the_topology_policy_is_the_one_the_fixture_describes() -> None:
    assert TOPOLOGY_POLICY.broker_wait_threshold == DEFAULT_BROKER_WAIT_THRESHOLD
    assert [_millis(d) for d in TOPOLOGY_POLICY.schedule()] == TOPOLOGY["policyScheduleMillis"]
    assert [
        _millis(d) for d in TOPOLOGY_POLICY.broker_rungs()
    ] == TOPOLOGY["policyRungDelaysMillis"]


async def test_the_whole_declared_plan_is_what_a_topology_produces() -> None:
    """Every exchange, queue and binding in the fixture, whoever declares it there.

    ``declaredBy`` records how Java splits the work: its ``Topology`` builds the
    source queue and the dead-letter side, and its consumer declares the retry
    exchange and the rungs when it starts. Python does not split it that way —
    ``Topology.queue(retry=policy)`` declares the rungs up front and the consumer
    declares nothing at all (see
    :func:`test_the_python_consumer_declares_nothing_of_its_own`). One call here
    therefore produces all three groups, and asserting that is the honest reading
    of the field rather than a looser one.
    """
    transport = await _declared(retry=TOPOLOGY_POLICY)

    assert {name: (spec.kind, spec.durable) for name, spec in transport.exchanges.items()} == {
        entry["name"]: (entry["type"], entry["durable"])
        for entry in _expect(TOPOLOGY["exchanges"], "topology", "consumer", "both")
    }
    assert {name: _queue_shape(spec) for name, spec in transport.queues.items()} == {
        entry["name"]: (entry["type"], entry["durable"], entry["arguments"])
        for entry in _expect(TOPOLOGY["queues"], "topology", "consumer", "both")
    }
    assert set(transport.bindings) == {
        (entry["queue"], entry["exchange"], entry["routingKey"])
        for entry in _expect(TOPOLOGY["bindings"], "topology", "consumer", "both")
    }


async def test_without_a_policy_a_topology_declares_only_the_half_that_is_not_retry() -> None:
    """The ``topology`` and ``both`` groups, and nothing from ``consumer``.

    Neither half is the whole topology, which is why the fixture labels every
    entry: a service that declares its queue and its dead-letter queue but no
    rungs is a working service right up to the first long backoff, at which point
    the wait quietly moves back into the consumer.
    """
    transport = await _declared(retry=None)

    assert set(transport.exchanges) == {
        entry["name"] for entry in _expect(TOPOLOGY["exchanges"], "topology", "both")
    }
    assert {name: _queue_shape(spec) for name, spec in transport.queues.items()} == {
        entry["name"]: (entry["type"], entry["durable"], entry["arguments"])
        for entry in _expect(TOPOLOGY["queues"], "topology", "both")
    }
    assert set(transport.bindings) == {
        (entry["queue"], entry["exchange"], entry["routingKey"])
        for entry in _expect(TOPOLOGY["bindings"], "topology", "both")
    }

    for entry in _expect(TOPOLOGY["queues"], "consumer"):
        assert entry["name"] not in transport.queues


async def test_the_python_consumer_declares_nothing_of_its_own() -> None:
    """Where this library's split differs from the one ``declaredBy`` records.

    Java's consumer declares the retry exchange and the rungs it is about to use.
    Python's consumer declares nothing: it publishes to a rung and, when the
    broker cannot route it, counts ``acemq.consumer.rung_missing``, says so, and
    falls back to waiting in the consumer. The rungs must therefore be in the
    topology, which is why ``Topology.queue`` takes the policy rather than a list
    of delays.
    """
    transport = await _declared(retry=TOPOLOGY_POLICY)

    def recorded() -> tuple[dict[str, Any], dict[str, Any], list[tuple[str, str, str]]]:
        return (
            dict(transport.queues),
            dict(transport.exchanges),
            list(transport.bindings),
        )

    before = recorded()

    async def handler(message: Message) -> Ack:
        return accept()

    connection = Connection(transport, retry=TOPOLOGY_POLICY)
    try:
        await connection.consume(TOPOLOGY["sourceQueue"], handler)
    finally:
        await connection.close()

    assert recorded() == before


async def test_the_rungs_a_topology_declares_are_the_ones_the_policy_names() -> None:
    """The link the fixture's ``consumer`` group depends on.

    A rung the topology declares under a name the consumer will not publish to is
    a queue nobody uses and a retry that quietly waits in the consumer, so the
    delays and the names have to come from one value.
    """
    transport = await _declared(retry=TOPOLOGY_POLICY)
    for delay in TOPOLOGY_POLICY.broker_rungs():
        rung = naming.retry_queue(TOPOLOGY["sourceQueue"], delay)
        assert rung in transport.queues
        assert dict(transport.queues[rung].args) == rung_args(TOPOLOGY["sourceQueue"], delay)


