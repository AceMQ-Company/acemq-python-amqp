def test_every_rung_dead_letters_home_through_the_managed_exchange() -> None:
    # Read as a rule rather than row by row: the time-to-live is the delay, the
    # target is the retry exchange, and the routing key is the queue the message
    # came from. Python used to dead-letter a rung through the default exchange,
    # which works and is not what the other four do.
    for row in RUNG_ARGUMENTS:
        assert row["arguments"]["x-message-ttl"] == row["delayMillis"]
        assert row["arguments"]["x-dead-letter-exchange"] == RETRY_EXCHANGE
        assert row["arguments"]["x-dead-letter-routing-key"] == QUEUE


