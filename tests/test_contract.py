@pytest.fixture
def _repeatable_jitter() -> Iterator[None]:
    """A seeded random source, so a bound this test asserts cannot pass by luck."""
    state = random.getstate()
    random.seed(20260908)
    yield
    random.setstate(state)


def test_the_jitter_factor_is_the_one_the_fixture_names() -> None:
    policy = _policy_from(_named(JITTER["policy"])["how"])
    assert policy.jitter_factor == JITTER["factor"]

    # The multipliers are the factor either side of one rather than two more
    # numbers to trust, which is what "applies in both directions" means.
    assert JITTER["appliesInBothDirections"] is True
    assert JITTER["minMultiplier"] == pytest.approx(1 - JITTER["factor"])
    assert JITTER["maxMultiplier"] == pytest.approx(1 + JITTER["factor"])


@pytest.mark.usefixtures("_repeatable_jitter")
def test_a_wait_spent_here_is_moved_both_ways_and_stays_inside_the_bounds() -> None:
    """Sampled, not read back.

    The fixture states the bounds; this asks the library for two thousand waits
    and checks that they land inside them, that both directions are used, and
    that none falls below the floor.
    """
    assert JITTER["appliesToConsumerWaits"] is True
    schedule = _named(JITTER["policy"])
    policy = _policy_from(schedule["how"])
    base = schedule["scheduleMillis"][0]
    assert not policy.waits_in_broker(timedelta(milliseconds=base))

    low = base * JITTER["minMultiplier"]
    high = base * JITTER["maxMultiplier"]
    seen = []
    for _ in range(2000):
        wait = policy.next_wait(1)
        assert wait is not None
        assert wait.in_broker is False
        millis = wait.delay.total_seconds() * 1000
        assert low <= millis <= high, f"{millis}ms is outside [{low}, {high}]"
        assert millis >= JITTER["flooredAtMillis"]
        seen.append(millis)

    assert min(seen) < base, "jitter never moved a wait earlier"
    assert max(seen) > base, "jitter never moved a wait later"
    # A herd that failed together must not come back together, which is the whole
    # point: two thousand draws should not be two thousand of the same number.
    assert len(set(seen)) > 1000


@pytest.mark.usefixtures("_repeatable_jitter")
def test_a_wait_the_broker_holds_is_never_moved() -> None:
    """A jittered delay would name a rung queue that does not exist.

    ``exponential-capped`` reaches 40s on its third attempt, which is above the
    threshold, so the wait is spent on ``orders.new.retry.40s`` — a queue whose
    time-to-live was fixed when it was declared.
    """
    assert JITTER["appliesToBrokerWaits"] is False
    schedule = _named("exponential-capped")
    policy = _policy_from(schedule["how"])
    scheduled = schedule["scheduleMillis"][2]
    assert policy.waits_in_broker(timedelta(milliseconds=scheduled))
    assert policy.jitter_factor > 0

    for _ in range(500):
        wait = policy.next_wait(3)
        assert wait is not None
        assert wait.in_broker is True
        assert _millis(wait.delay) == scheduled


