"""The retry schedule, the queue names and the topology, against every language.

``contract-fixtures.json`` is generated by the Java library and committed
byte-for-byte by all five. It exists because every library used to test its own
arithmetic against its own expectations, which is a test that passes for as long
as the library is self-consistent and says nothing at all about whether the
libraries agree. Java shipped ``exponential`` with a multiplier of 5.0 and 10%
jitter through ten releases while Go, .NET, Python and Ruby doubled with 20%:
``exponential(5, 1s, 1m)`` produced ``1s, 5s, 25s, 60s`` there and
``1s, 2s, 4s, 8s`` here, and nothing failed anywhere. Three more divergences —
the retry rung's dead-letter exchange, the source queue's dead-letter arguments,
and the queue type — turned up the same way on the same afternoon, all four
found by a person reading five codebases side by side rather than by a suite.

Reading a number out of the fixture and comparing it to the same number read out
of this library would prove only that both can be read, so the expectations here
are derived wherever there is a second way to reach them: the policies are built
from the fixture's own ``how`` string rather than from a table written beside it,
the doubling is checked as arithmetic rather than as a list, the broker-wait
table is recomputed from the stated rule, and the rung names are rendered by a
second implementation written from the naming convention.

Two places where this library does not match the file are asserted as
divergences rather than smoothed over. Both are documented on the tests that
carry them: the sub-second rung name, which the fixture itself records as
unresolved, and the default maximum message age, which it does not.
"""

