@pytest.mark.parametrize(
    "asked",
    [{"exclusive": True}, {"auto_delete": True}, {"durable": False}],
    ids=["exclusive", "auto-delete", "transient"],
)
async def test_a_queue_that_belongs_to_one_connection_stays_classic(
    asked: dict[str, Any],
) -> None:
    """The rule the fixture says Java cannot be asked about.

    ``queueTypeDefaults.durability`` records that the Java API offers no way to
    declare an exclusive, auto-delete or transient queue, so the rule that such a
    queue stays classic has nothing to attach to there and the ports that do
    offer the flags have to keep it. Python offers all three; this is that half of
    the contract being kept.
    """
    recorded = QUEUE_TYPES["durability"]["exclusiveAutoDeleteOrTransient"]
    assert "must keep them classic" in recorded

    transport = await _one_queue(**asked)
    assert QUEUE_TYPE_ARG not in transport.queues[QUEUE].args
    assert _kind(transport, QUEUE) == "classic"
