@pytest.mark.parametrize("schedule", SCHEDULES, ids=_schedule_id)
def test_a_schedule_has_one_delay_fewer_than_it_has_attempts(
    schedule: dict[str, Any],
) -> None:
    # Derived rather than read: the last attempt is not followed by a wait, so
    # ``max_attempts`` deliveries need ``max_attempts - 1`` delays. This is what
    # caught nothing and would have caught the multiplier bug had anyone looked.
    policy = _policy_from(schedule["how"])
    assert len(policy.schedule()) == policy.max_attempts - 1


@pytest.mark.parametrize("schedule", SCHEDULES, ids=_schedule_id)
def test_each_delay_is_its_predecessor_multiplied_until_the_ceiling(
    schedule: dict[str, Any],
) -> None:
    """The arithmetic, checked as arithmetic.

    This is the assertion Java did not have. ``exponential`` doubles and ``fixed``
    repeats, and the ceiling clamps whatever the multiplier would have produced —
    so each delay is ``min(previous * multiplier, ceiling)`` and no list of
    numbers has to be trusted to say so.
    """
    how = schedule["how"]
    match = _HOW.fullmatch(how)
    assert match is not None
    args = [part.strip() for part in match["args"].split(",") if part.strip()]

    if match["kind"] == "none":
        assert schedule["scheduleMillis"] == []
        return

    multiplier = 2 if match["kind"] == "exponential" else 1
    ceiling = _millis(_duration(args[2])) if len(args) > 2 else 0

    delays = schedule["scheduleMillis"]
    assert delays[0] == _millis(_duration(args[1]))
    for previous, delay in pairwise(delays):
        expected = previous * multiplier
        if ceiling and expected > ceiling:
            expected = ceiling
        assert delay == expected, f"{how}: {delay} does not follow {previous}"


@pytest.mark.parametrize("schedule", SCHEDULES, ids=_schedule_id)
def test_the_rungs_are_the_distinct_long_waits_in_the_order_they_are_reached(
    schedule: dict[str, Any],
) -> None:
    policy = _policy_from(schedule["how"])
    rungs = [_millis(delay) for delay in policy.broker_rungs()]
    assert rungs == schedule["brokerRungDelaysMillis"]

    # And the same list worked out from the schedule and the threshold, which is
    # the definition rather than a second reading of the answer. A fixed policy
    # that waits a minute three times needs one queue, not three.
    threshold = schedule["brokerWaitThresholdMillis"]
    expected: list[int] = []
    for delay in schedule["scheduleMillis"]:
        if _waits_in_broker_by_the_rule(delay, threshold) and delay not in expected:
            expected.append(delay)
    assert schedule["brokerRungDelaysMillis"] == expected


@pytest.mark.parametrize("schedule", SCHEDULES, ids=_schedule_id)
def test_the_attempt_and_age_limits_decide_the_same_way(schedule: dict[str, Any]) -> None:
    """Every ``{attempt, messageAgeMillis, retries}`` row the fixture records.

    No row is exempt. Six used to be: Java defaulted a policy to a 365-day age
    limit where the other four defaulted to none, so the fixture said a year-old
    message was abandoned and this library retried it. Java now agrees that zero
    means no limit, and the exemption went with the divergence.
    """
    policy = _policy_from(schedule["how"])
    for decision in schedule["decisions"]:
        age = timedelta(milliseconds=decision["messageAgeMillis"])
        retries = policy.next_wait(decision["attempt"], age) is not None
        assert retries == decision["retries"], (
            f"{schedule['name']}: attempt {decision['attempt']} at age "
            f"{decision['messageAgeMillis']}ms"
        )
        # next_delay is the same decision with the location thrown away, and a
        # library where the two could disagree would retry in one code path and
        # dead-letter in the other.
        assert (policy.next_delay(decision["attempt"], age) is not None) == retries


def test_no_policy_carries_an_age_limit_nobody_asked_for() -> None:
    """The agreement that replaced a divergence.

    Java used to build every policy with ``Duration.ofDays(365)`` and compare
    against it unconditionally, so a message exactly a year old was abandoned by
    a policy nobody asked to give up on age, while Go, .NET, Ruby and this
    library all read zero as no limit and kept retrying. Four to one, and the
    fixture recorded Java's answer. Java moved: zero is the default and only
    ``giveUpAfter`` sets a limit.

    So this asserts the agreement rather than bounding a disagreement, and it
    fails if it ever exercises nothing — a test that quietly stops running is
    how the divergence it replaced survived ten releases.
    """
    a_year = timedelta(days=365)
    checked = 0
    for schedule in SCHEDULES:
        if schedule["hasMaxMessageAge"]:
            continue  # asked for a limit; the boundary test owns those

        assert schedule["maxMessageAgeMillis"] == 0, (
            f"{schedule['name']} has no age limit but records "
            f"{schedule['maxMessageAgeMillis']}ms; zero is how the fixture says "
            "unlimited, and hasMaxMessageAge is how it says which zero it means"
        )

        policy = _policy_from(schedule["how"])
        assert policy.max_message_age == ZERO

        if schedule["maxAttempts"] < 2:
            continue  # no_retry stops on attempts before age can matter

        assert policy.next_wait(1, a_year) is not None, (
            f"{schedule['name']} gave up on a year-old message; with no age "
            "limit it should still retry"
        )
        checked += 1

    assert checked, "no unlimited policy was exercised, so this proved nothing"


def test_an_age_limit_that_was_asked_for_is_honoured_to_the_millisecond() -> None:
    """The half of the age rule the libraries do agree on.

    ``giveUpAfter`` is inclusive: a message that has just reached the limit is
    abandoned, one a millisecond short of it is not. That boundary is what the
    ``exponential-give-up-on-age`` rows are for, and every library implements it
    as ``age >= limit``.
    """
    schedule = _named("exponential-give-up-on-age")
    policy = _policy_from(schedule["how"])
    limit = schedule["maxMessageAgeMillis"]
    assert _millis(policy.max_message_age) == limit

    assert policy.next_wait(1, timedelta(milliseconds=limit - 1)) is not None
    assert policy.next_wait(1, timedelta(milliseconds=limit)) is None


