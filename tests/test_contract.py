# --------------------------------------------------------------------------- #
# Reading the fixture's own descriptions, so nothing is copied by hand
# --------------------------------------------------------------------------- #

_UNIT_SECONDS = {"ms": 0.001, "h": 3600.0, "m": 60.0, "s": 1.0}

_HOW = re.compile(
    r"(?P<kind>exponential|fixed|none)\((?P<args>[^)]*)\)"
    r"(?:\.giveUpAfter\((?P<age>[^)]+)\))?"
)


def _duration(text: str) -> timedelta:
    """``1s``, ``24h``, ``500ms`` as a duration.

    Longest suffix first, so ``ms`` is not read as ``m`` followed by rubbish.
    """
    for suffix, seconds in _UNIT_SECONDS.items():
        if text.endswith(suffix):
            return timedelta(seconds=float(text[: -len(suffix)]) * seconds)
    raise ValueError(f"the fixture describes a duration this test cannot read: {text!r}")


def _policy_from(how: str) -> RetryPolicy:
    """The policy the fixture says it is describing, built from that description.

    The alternative is a table of policies written beside the fixture, which is a
    second copy of the same list and free to drift from it — and the drift would
    show up as a suite that agrees with itself about the wrong policy.
    """
    match = _HOW.fullmatch(how)
    if match is None:
        raise ValueError(f"the fixture describes a policy this test cannot build: {how!r}")
    args = [part.strip() for part in match["args"].split(",") if part.strip()]

    policy: RetryPolicy
    if match["kind"] == "none":
        policy = no_retry()
    elif match["kind"] == "fixed":
        policy = fixed_retry(int(args[0]), _duration(args[1]))
    else:
        ceiling = _duration(args[2]) if len(args) > 2 else ZERO
        policy = exponential_retry(int(args[0]), _duration(args[1]), ceiling)

    if match["age"] is not None:
        policy = policy.give_up_after(_duration(match["age"]))
    return policy


def _millis(delay: timedelta) -> int:
    return round(delay.total_seconds() * 1000)


def _named(name: str) -> dict[str, Any]:
    """One entry of ``retrySchedules`` by name."""
    for schedule in SCHEDULES:
        if schedule["name"] == name:
            return schedule
    raise AssertionError(f"the fixture has no policy called {name!r}")


def _schedule_id(schedule: dict[str, Any]) -> str:
    return str(schedule["name"])


# --------------------------------------------------------------------------- #
# Second implementations, written from the rule rather than from the library
# --------------------------------------------------------------------------- #


def _waits_in_broker_by_the_rule(delay_millis: int, threshold_millis: int) -> bool:
    """``brokerWaitThreshold.rule``, transcribed.

    "A wait at or above the threshold is held on a rung queue; anything below it,
    and anything zero or negative, is held in the consumer. A threshold of zero
    sends nothing to the broker."
    """
    if threshold_millis <= 0:
        return False
    if delay_millis <= 0:
        return False
    return delay_millis >= threshold_millis


def _rendered_by_hand(delay: timedelta) -> str:
    """The delay suffix of a rung name, from the convention rather than the code.

    Whole hours read as hours, whole minutes as minutes, anything else as
    seconds, and a delay that does not reach a second has no seconds to show.
    """
    seconds = int(delay.total_seconds())
    if seconds <= 0:
        return "0s"
    if seconds % 3600 == 0:
        return f"{seconds // 3600}h"
    if seconds % 60 == 0:
        return f"{seconds // 60}m"
    return f"{seconds}s"


def _queue_shape(spec: QueueSpec) -> tuple[str, bool, dict[str, Any]]:
    """A declared queue as the fixture describes one: type, durability, arguments.

    ``x-queue-type`` moves out of the arguments and becomes the type, because a
    classic queue is declared by leaving the argument off entirely — the spelling
    every AceMQ library sends — and the fixture records that absence as
    ``"classic"`` rather than as a missing key.
    """
    args = dict(spec.args)
    kind = str(args.pop(QUEUE_TYPE_ARG, "classic"))
    return kind, spec.durable, args


